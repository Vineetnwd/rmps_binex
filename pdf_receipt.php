<?php
error_reporting(E_ALL);
require_once('system/function.php');
require_once('fpdf/fpdf.php'); // Include FPDF library

// Verify request and get receipt ID
verify_request();
$rid = $_REQUEST['receipt_id'];

// Fetch data
if (get_data('receipt', $rid)['count'] > 0) {
    $receipt = get_data('receipt', $rid)['data'];
    $student = get_data('student', $receipt['student_id'])['data'];
    $branch = get_data('branch_list', $receipt['branch_id'])['data'];
}

// Initialize PDF
class PDF extends FPDF {
    function Header() {
        // Add logo
        $this->Image('assets/images/logo.png', 10, 10, 30); // Adjust size and position
    }

    function Footer() {
        $this->SetY(-15);
        $this->SetFont('Arial', 'I', 8);
        $this->Cell(0, 10, 'Auto-generated receipt for information purposes only', 0, 0, 'C');
    }
}

$pdf = new PDF('P', 'mm', 'A4'); // Portrait, millimeters, A4 size
$pdf->AddPage();
$pdf->SetAutoPageBreak(true, 20);

// Set font
$pdf->SetFont('Arial', '', 10);

// School Header

$pdf->SetFont('Arial', 'B', 18);
$pdf->Cell(0, 8, $full_name, 0, 1, 'C');
$pdf->SetFont('Arial', '', 10);
$pdf->Cell(0, 6, $aff_to, 0, 1, 'C');
$pdf->SetFont('Arial', 'B', 10);
$pdf->Cell(0, 6, "Aff. No.: $aff_no  School Code: $school_code", 0, 1, 'C');
$pdf->SetFont('Arial', '', 10);
$pdf->Cell(0, 6, $branch['inst_address1'] . ' ' . $branch['inst_address2'], 0, 1, 'C');
$pdf->Cell(0, 6, "Contact: " . $branch['inst_contact'] . " | Website: " . $inst_url, 0, 1, 'C');
$pdf->Ln(5);

// Receipt Info
$pdf->SetFillColor(245, 245, 245); // Light gray for background
$pdf->SetFont('Arial', 'B', 10);
$status_class = $receipt['status'] == 'CANCEL' ? 'CANCEL' : $receipt['status'];
$pdf->Cell(100, 8, "Receipt No.: $rid-$status_class", 1, 0, 'L', true);
$pdf->Cell(90, 8, date('d-M-Y h:i A', strtotime($receipt['created_at'])), 1, 1, 'R', true);
$pdf->Cell(190, 8, "Fee Details of " . add_space(str_replace(',', ', ', $receipt['paid_month'])), 1, 1, 'C');

// Student Info
$pdf->SetFont('Arial', '', 10);
$pdf->Cell(60, 8, 'Name', 1, 0);
$pdf->Cell(130, 8, strtoupper($student['student_name']), 1, 1);
$pdf->Cell(60, 8, 'Student ID', 1, 0);
$pdf->Cell(130, 8, strtoupper($student['student_admission']), 1, 1);
$pdf->Cell(60, 8, "Father's Name", 1, 0);
$pdf->Cell(130, 8, strtoupper($student['student_father']), 1, 1);
$pdf->Cell(30, 8, 'Class', 1, 0);
$pdf->Cell(130, 8, $student['student_class'] . '-' . $student['student_section'] . ' (' . $student['student_type'] . ')', 1, 0);
$pdf->Cell(30, 8, 'Roll No.: ' . $student['student_roll'], 1, 1);

// Fee Breakdown
$pdf->SetFont('Arial', '', 10);
$previous_dues = get_data('receipt', $rid, 'previous_dues')['data'];
$fee_items = [];
if ($previous_dues != 0) {
    $fee_items[] = ['name' => 'Previous Dues', 'amount' => $previous_dues];
}

// Fetch active fee heads
$res = get_all('fee_head', '*', array('status' => 'ACTIVE'));
if ($res['status'] == 'success') {
    foreach ($res['data'] as $row) {
        $col_name = remove_space($row['fee_name']);
        $amount = get_data('receipt', $rid, $col_name)['data'];
        if ($amount > 0) {
            $fee_items[] = ['name' => $row['fee_name'], 'amount' => $amount];
        }
    }
}
if ($receipt['other_fee'] != 0) {
    $fee_items[] = ['name' => 'Miscellaneous Fee', 'amount' => $receipt['other_fee']];
}

// Display fee items
$y = $pdf->GetY();
$pdf->Rect(10, $y, 190, 50); // Rectangle for fee table
foreach ($fee_items as $item) {
    $pdf->SetX(10);
    $pdf->Cell(150, 8, $item['name'], 0, 0);
    $pdf->Cell(40, 8, $item['amount'], 0, 1, 'R');
}

// Move to bottom of fee table
$pdf->SetY($y + 50);
if (!empty($receipt['remarks'])) {
    $pdf->Cell(190, 8, 'Remarks: ' . $receipt['remarks'], 1, 1, 'C');
}
if ($receipt['discount'] != 0) {
    $pdf->Cell(150, 8, 'Discount (-)', 1, 0, 'R');
    $pdf->Cell(40, 8, $receipt['discount'], 1, 1, 'R');
}
$pdf->Cell(150, 8, 'Total', 1, 0, 'R');
$pdf->Cell(40, 8, $receipt['total'], 1, 1, 'R');

// Paid Amount
$pdf->SetFillColor(214, 214, 214); // Darker gray for paid amount
$pdf->SetFont('Arial', 'B', 12);
$pdf->Cell(150, 10, 'Paid Amount (In ' . $receipt['payment_mode'] . ')', 1, 0, 'R', true);
$pdf->Cell(40, 10, $receipt['paid_amount'], 1, 1, 'R', true);

// Amount in Words
$pdf->SetFont('Arial', '', 10);
$pdf->Cell(190, 8, 'Amount in Words: ' . amount_in_word($receipt['paid_amount']) . ' Only', 1, 1);

// Current Dues
$pdf->SetTextColor(255, 0, 0); // Red for current dues
$pdf->Cell(150, 8, 'Current Dues', 1, 0);
$pdf->Cell(40, 8, $receipt['current_dues'], 1, 1, 'R');
$pdf->SetTextColor(0); // Reset to black

// Instructions
$pdf->SetFont('Arial', '', 8);
$pdf->MultiCell(190, 5, "Instructions:\n- Please pay before 10th of every month.\n- Always update your mobile no. to receive notification.\n- This receipt is auto-generated by computer for information purposes only.", 1);

// Issued By and Signatory
$pdf->SetFont('Arial', '', 10);
$issued_by = get_data('user', get_data('receipt', $rid, 'created_by')['data'], 'user_name')['data'];
$pdf->Cell(95, 8, 'Issued by: ' . $issued_by, 1, 0);
$pdf->Cell(95, 8, 'Authorised Signatory', 1, 1, 'R');

// Output PDF
$pdf->Output('D', 'Receipt_'.$rid.'.pdf'); // Display in browser
?>